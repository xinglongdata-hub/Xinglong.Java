package com.xinglong.For;

public class Demo02For {
    public static void main(String[] args) {
        //定义一个变量来接收两个数据的和 sum
        int sum = 0 ;
        for (int i = 1; i <=100; i++) {
            //再循环的过程中 两两相加，再赋值给sum
            sum +=1;
            //输出sum
            System.out.println("sum = " + sum);


        }

    }

}
