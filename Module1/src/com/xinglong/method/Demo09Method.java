package com.xinglong.method;

/*
定义一个方法，给这个方法传几，就让这个方法打印几次
 */
public class Demo09Method {
    public static void main(String[] args) {
        method(10);
    }
    public static void method(int n){
        for (int i = 0; i < n; i++) {
            System.out.println("我是一位有检验的Java开发工程师也是ai应用开发工程师和全栈开发工程师");
        }
    }
}
